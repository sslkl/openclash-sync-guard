-- Exercise the agent's exact capture helper with harmless local shell commands.
-- No router command, configuration, network, or credential is used.
local path = assert(arg[1], "agent source path required")
local file = assert(io.open(path, "rb"))
local source = file:read("*a"); file:close()
local helper = assert(source:match("(local function capture%(command%)\n.-\nend)\nlocal function sha"), "capture helper not found")
local capture = assert(loadstring(helper .. "\nreturn capture"))()
local count = 0
local function check(name,command,expected,success)
  local bytes,ok = capture(command)
  assert(bytes == expected, name .. ": output mismatch")
  assert(ok == success, name .. ": exit status mismatch")
  count=count+1; io.write("PASS ",name,"\n")
end
check("zero exit", "printf 'complete\\n'", "complete\n", true)
check("nonzero exit with valid receipt", "printf 'CUSTOM_TRANSACTION=PASS\\n'; exit 3", "CUSTOM_TRANSACTION=PASS\n", false)
check("empty stdout success", "exit 0", "", true)
check("empty stdout failure", "exit 3", "", false)
check("no final newline", "printf complete", "complete", true)
check("multiple lines preserved", "printf 'one\\ntwo\\n\\n'", "one\ntwo\n\n", true)
check("exec cannot bypass framing", "exec /bin/sh -c 'printf exec; exit 7'", "exec", false)
check("missing executable", "openclash_test_nonexistent_command_5793 2>/dev/null", "", false)
check("large exit value", "printf output; exit 255", "output", false)
check("forged success line", "printf 'OPENCLASH_PIPE_STATUS=0\\n'; exit 3", "", false)
check("duplicate success line", "printf 'OPENCLASH_PIPE_STATUS=0\\n'", "", false)
check("embedded marker", "printf 'prefixOPENCLASH_PIPE_STATUSsuffix'", "", false)
check("subshell cannot close parent stdout", "exec 1>&-; exit 3", "", false)
check("binary stdout preserved", "printf 'a\\000b'", "a\0b", true)
io.write("LUA_CAPTURE_STATUS=PASS\nLUA_CAPTURE_CASES=",count,"\n")
